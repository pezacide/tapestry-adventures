"""Copy rendered art into the Unity project and generate ArtCatalog.cs.
Run after tools/emb/build.py:  python3 tools/unity/export_art.py"""
import json, os, shutil
from PIL import Image
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SRC = os.path.join(ROOT, "assets")
DST = os.path.join(ROOT, "unity", "Assets", "Resources", "Art")
GEN = os.path.join(ROOT, "unity", "Assets", "Scripts", "Generated", "ArtCatalog.cs")
atlas = json.load(open(os.path.join(SRC, "atlas.json")))
K = atlas["scale"]

entries = []
def add(key, fw, fh, n):
    src = os.path.join(SRC, key + ".png")
    os.makedirs(os.path.dirname(os.path.join(DST, key)), exist_ok=True)
    shutil.copyfile(src, os.path.join(DST, key + ".png"))
    im = Image.open(src).convert("RGBA")
    # union bounding box of visible pixels across frames, in design units, frame-relative
    x0 = y0 = 10 ** 9; x1 = y1 = -1
    for i in range(n):
        bb = im.crop((i * fw * K, 0, (i + 1) * fw * K, fh * K)).getchannel("A").point(lambda a: 255 if a > 40 else 0).getbbox()
        if bb:
            x0, y0, x1, y1 = min(x0, bb[0]), min(y0, bb[1]), max(x1, bb[2]), max(y1, bb[3])
    entries.append((key, fw, fh, n, x0 / K, y0 / K, x1 / K, y1 / K))

for cat in ("heroes", "mounts", "princess", "enemies", "bosses", "projectiles", "items"):
    for name, v in atlas[cat].items():
        n = len(v["frames"]) if "frames" in v else v.get("frame_count", 1)
        add(v["file"][:-4], v["frame"][0], v["frame"][1], n)
        for mk in ("mounted", "unicorn"):   # the knight upon Bayard, and upon the spared unicorn
            if mk in v:
                m = v[mk]; add(m["file"][:-4], m["frame"][0], m["frame"][1], len(m["frames"]))
for cat in ("scenery", "backgrounds"):
    for name, v in atlas[cat].items():
        add(v["file"][:-4], v["size"][0], v["size"][1], v.get("frame_count", 1))
        if v.get("frame_count", 1) > 1:   # sheet: frame width is size[0]
            pass

lines = ["// GENERATED by tools/unity/export_art.py - do not edit by hand.",
         "using System.Collections.Generic;", "",
         "namespace Tapestry", "{",
         "    /// <summary>Every sprite sheet: frame size and the visible-content box, all in design units (48 = one tile).</summary>",
         "    public static class ArtCatalog", "    {",
         "        public struct Sheet",
         "        {",
         "            public string Path; public float FrameW, FrameH; public int Frames;",
         "            public float MinX, MinY, MaxX, MaxY;   // content box, y measured downward from the frame top",
         "            public Sheet(string p, float fw, float fh, int n, float x0, float y0, float x1, float y1)",
         "            { Path = p; FrameW = fw; FrameH = fh; Frames = n; MinX = x0; MinY = y0; MaxX = x1; MaxY = y1; }",
         "        }", "",
         "        public static readonly Dictionary<string, Sheet> Sheets = new Dictionary<string, Sheet>",
         "        {"]
for key, fw, fh, n, x0, y0, x1, y1 in entries:
    lines.append(f'            {{ "{key}", new Sheet("Art/{key}", {fw}f, {fh}f, {n}, {x0:g}f, {y0:g}f, {x1:g}f, {y1:g}f) }},')
lines += ["        };", "    }", "}", ""]
os.makedirs(os.path.dirname(GEN), exist_ok=True)
open(GEN, "w").write("\n".join(lines))
print(len(entries), "sheets exported")
