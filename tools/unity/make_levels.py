"""Lay out the levels and write each as an ASCII map in C# (unity/Assets/Scripts/Levels/LevelN.cs).
Legend:  # earth   B brick (breaks)   ? brick hiding a bezant   H brick hiding Bayard   = plank (one-way)
         1 brick hiding a golden chalice (life)   M roast capon (heart)   W crossbowe   R holy relique (star)
         Q log pile (rolls logs at the knight)   g gull   x crab   f fish   z sea-serpent   m sea-monk
         * fire pit   _ drawbridge   F flail block   A axe (drops the bridge)   K boss   N rescued monk
         V vault stone (unbreakable)   L lift gliding sideways   E lift rising and falling (both 3 wide, from that tile)
         ^ treetop (one-way)   | tree trunk (scenery)   T/t tower top/body (2 wide)   ~ sea   o bezant
         P start   G goal pole   C halfway banner (respawn point)
         s snail-hound (red shell: kick it)  S mossy snail-hound (green shell: pick up and throw)  h killer hare  l fiery lion  d bayeux hound  c camel-dragon
         w wyvern  u unicorn  O man-faced owl  k soup cat"""
import os
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "unity", "Assets", "Scripts", "Levels")

class Map:
    def __init__(self, w=200, h=12):
        self.W, self.H = w, h
        self.g = [[" "] * w for _ in range(h)]
    def put(self, x, y, ch): self.g[y][x] = ch
    def ground(self, x0, x1):
        for x in range(x0, x1 + 1): self.put(x, 0, "#"); self.put(x, 1, "#")
    def water(self, x0, x1):
        for x in range(x0, x1 + 1): self.put(x, 0, "~"); self.put(x, 1, "~")
    def tower(self, x, h):
        for y in range(2, 2 + h - 1): self.put(x, y, "t"); self.put(x + 1, y, "t")
        self.put(x, 2 + h - 1, "T"); self.put(x + 1, 2 + h - 1, "T")
    def row(self, x0, y, s):
        for i, ch in enumerate(s):
            if ch != " ": self.put(x0 + i, y, ch)
    def stairs(self, x0, n):
        for i in range(n):
            for y in range(2, 2 + i + 1): self.put(x0 + i, y, "B")
    def treetop(self, x0, w, top):
        """A tree: a canopy you can stand on at row `top`, trunk down to the ground (or the pit)."""
        for x in range(x0, x0 + w): self.put(x, top, "^")
        cx = x0 + w // 2
        for y in range(0, top):
            if self.g[y][cx] == " ": self.put(cx, y, "|")
    def vault(self, x0, x1, y0=9, y1=11):
        for x in range(x0, x1 + 1):
            for y in range(y0, y1 + 1): self.put(x, y, "V")
    def pillar(self, x, bottom, w=1):
        """Vault stone hanging from the ceiling down to row `bottom` (leave >= 2 rows of headroom below it)."""
        for xx in range(x, x + w):
            for y in range(bottom, 9): self.put(xx, y, "V")
    def floor(self, x0, x1):
        for x in range(x0, x1 + 1): self.put(x, 0, "V"); self.put(x, 1, "V")
    def fire(self, x0, x1, top=1):
        for x in range(x0, x1 + 1):
            for y in range(0, top + 1): self.put(x, y, "*")
    def rows(self): return ["".join(self.g[y]).rstrip() for y in range(self.H - 1, -1, -1)]

def write(cls, title, name, inscription, m, props, castle, castle_x, music, far=None, near=None, entrance=False, skin=None, vault=None, underwater=False, end_at_door=False):
    castle = castle or ""
    cs = [f"// GENERATED by tools/unity/make_levels.py - edit the script to change the level.",
          "namespace Tapestry", "{", f"    public static class {cls}", "    {",
          "        public static readonly LevelDef Def = new LevelDef", "        {",
          f'            Title = "{title}",', f'            Name = "{name}",', f'            Inscription = "{inscription}",',
          f'            Castle = "{castle}", CastleX = {castle_x}f,', f'            Music = "{music}",']
    if far: cs.append(f'            FarLayer = "{far}", NearLayer = "{near}",')
    if entrance: cs.append('            Entrance = true,   // no pole: walking into the building leads on to the next part')
    if skin: cs.append(f'            GroundTop = "{skin[0]}", GroundFill = "{skin[1]}", Brick = "{skin[2]}",')
    if vault: cs.append(f'            Vault = "{vault}",')
    if underwater: cs.append('            Underwater = true,')
    if end_at_door: cs.append('            EndAtDoor = true,')
    cs.append("            Map = new[]"); cs.append("            {")
    cs += [f'                "{r}",' for r in m.rows()]
    cs += ["            },", "            Props = new Decor[]", "            {"]
    cs += [f'                new Decor("scenery/{k}", {x}),' for k, x in props]
    cs += ["            },", "        };", "    }", "}", ""]
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, cls + ".cs"), "w").write("\n".join(cs))
    print(f"== {cls}: {title} - {name}"); print("\n".join(m.rows()))

