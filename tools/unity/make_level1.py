"""Lay out World 1-1 'The Meadow of Beasts' and write it as an ASCII map in C#.
Legend:  # earth   B masonry   ? roundel (bezant)   H roundel (Bayard)   = plank (one-way)
         T/t tower top/body (2 wide)   ~ sea   o bezant   P start   G goal banner
         s snail-hound  h killer hare  l fiery lion  d bayeux hound  c camel-dragon
         w wyvern  u unicorn  O man-faced owl  k soup cat"""
import os
W, H = 200, 12
g = [[" "] * W for _ in range(H)]          # g[y][x], y=0 bottom
def put(x, y, ch): g[y][x] = ch
def ground(x0, x1):
    for x in range(x0, x1 + 1):
        put(x, 0, "#"); put(x, 1, "#")
def tower(x, h):                            # occupies x, x+1 ; rows 2..2+h-1
    for y in range(2, 2 + h - 1): put(x, y, "t"); put(x + 1, y, "t")
    put(x, 2 + h - 1, "T"); put(x + 1, 2 + h - 1, "T")
def row(x0, y, s):
    for i, ch in enumerate(s):
        if ch != " ": put(x0 + i, y, ch)

ground(0, 29); ground(33, 69); ground(77, 139); ground(144, 199)
for x in range(70, 77): put(x, 0, "~"); put(x, 1, "~")
put(3, 2, "P")
row(10, 5, "?"); row(14, 5, "B?BHB"); row(16, 8, "?")
put(15, 2, "s"); put(26, 2, "h")
tower(22, 2)
row(37, 5, "===="); row(37, 7, "oooo")
put(48, 2, "l")
tower(54, 3); put(58, 2, "d"); tower(62, 3)
row(71, 4, "==="); row(74, 6, "==="); row(71, 6, "ooo")
for i in range(5):                          # little masonry stair
    for y in range(2, 2 + i + 1): put(80 + i, y, "B")
put(88, 2, "c"); put(96, 7, "w")
row(100, 5, "B?B?B?B"); row(101, 8, "o o o")
put(112, 2, "u")
tower(124, 3); put(124, 5, "O")
row(130, 4, "BBBB"); put(132, 5, "k")
row(140, 5, "==="); row(140, 7, "ooo")
put(150, 2, "s"); put(154, 2, "h"); put(147, 7, "w")
for i in range(6):                          # Mario-style end staircase
    for y in range(2, 2 + i + 1): put(160 + i, y, "B")
put(176, 2, "G")

rows = ["".join(g[y]).rstrip() for y in range(H - 1, -1, -1)]
cs = ["// GENERATED by tools/unity/make_level1.py - edit the script (or this map) to change the level.",
      "namespace Tapestry", "{", "    public static class Level1", "    {",
      '        public const string Name = "The Meadow of Beasts";',
      '        public const string Inscription = "HIC MILITES INTRANT PRATUM BESTIARUM";',
      "        // Top row first. Legend in tools/unity/make_level1.py and Level.cs.",
      "        public static readonly string[] Map =", "        {"]
cs += [f'            "{r}",' for r in rows]
cs += ["        };", "",
       "        // Background props: sheet key and tile column (placed on the ground there).",
       "        public static readonly Decor[] Props =", "        {",
       '            new Decor("scenery/tree", 6), new Decor("scenery/shrub", 12), new Decor("scenery/hill", 25), new Decor("scenery/tree", 34), new Decor("scenery/shrub", 45),',
       '            new Decor("scenery/tree", 66), new Decor("scenery/hill", 86), new Decor("scenery/tree", 95), new Decor("scenery/shrub", 110), new Decor("scenery/hill", 128),',
       '            new Decor("scenery/shrub", 138), new Decor("scenery/tree", 150), new Decor("scenery/motte", 186), new Decor("scenery/tree", 172),',
       "        };", "    }", "}", ""]
p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "unity", "Assets", "Scripts", "Levels", "Level1.cs")
os.makedirs(os.path.dirname(p), exist_ok=True)
open(p, "w").write("\n".join(cs))
print("\n".join(rows))
